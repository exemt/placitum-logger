-- Срез запроса в самой записи: заголовки, параметры, префикс тела.
--
-- Это не дубль обменника. В store_* лежит адрес объекта, который живёт своим
-- сроком и достаётся по одной записи за раз; здесь — фиксированный по размеру
-- срез, по которому можно искать и фильтровать поперёк всех записей сразу.
-- Объём задан конфигурацией модуля (waf_preview), а не клиентом, поэтому
-- колонка не растёт от заголовка на мегабайт.
--
-- Карты, а не строки: спрашивают по имени — «все запросы с этим user-agent»,
-- «где параметр redirect непустой», — и карта отвечает на это точным
-- сравнением вместо разбора строки на каждой строке таблицы. Повторяющиеся
-- имена логгер склеивает через ", " по правилу составных заголовков.
--
-- Тело — строка: имени у него нет, а ищут в нём подстроку. Индекс по
-- lower(body_preview) обслуживает ровно это: ngrambf_v1 отсекает куски по
-- LIKE '%...%', но только когда выражение в запросе совпадает с выражением
-- индекса. positionCaseInsensitive его не включает — это разные функции с
-- точки зрения планировщика.
--
-- Признака обрезки здесь нет: секция обрывается целыми парами, а headers_count,
-- args_size и body_size уже описывают сам запрос, и превью сравнивается с ними.
-- Потолок на отдельную пару появился позже и сравнение сломал — признак завёлся
-- тогда же, в 011.

ALTER TABLE waf.audit
    ADD COLUMN IF NOT EXISTS headers_preview Map(LowCardinality(String), String),
    ADD COLUMN IF NOT EXISTS args_preview    Map(LowCardinality(String), String),
    ADD COLUMN IF NOT EXISTS body_preview    String,
    ADD INDEX IF NOT EXISTS idx_body_preview lower(body_preview)
        TYPE ngrambf_v1(3, 8192, 3, 0) GRANULARITY 4
