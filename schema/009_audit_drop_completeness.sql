-- Полнота склейки уезжает из позвоночника: колонок больше нет, и считать их
-- на записи логгер перестал.
--
-- Обе отвечали на вопрос «доехали ли до логгера детали находок», и ответить на
-- него на записи нельзя — можно только подождать и объявить, что не доехали.
-- Ради этого держались корзина склейки, окно ожидания, память о закрытых
-- записях и переиздание якоря с rev+1. Ценой был не только код: корзина живёт
-- в памяти процесса, а durable consumer у потока один на все реплики, поэтому
-- на втором логгере фрагменты одного запроса разъезжались, и каждая вторая
-- запись помечалась partial при живых и целых находках рядом.
--
-- Того, ради чего эту ось заводили, она не давала. «Инспектор не ответил на
-- волну» знает модуль, и он это пишет сам: inspectors_state = timeout и
-- code = fail_timeout. А доставка аудита до обменника — сантехника шины, не
-- признак инцидента.
--
-- Что осталось: события пишутся независимо, каждое своей строкой, и сводятся
-- на чтении в карточке (internal/query/card.go). «Вызвали, а строк находок
-- нет» там по-прежнему видно — по факту их отсутствия, а не по колонке.
--
-- rev остаётся: это версия ReplacingMergeTree, снять её без пересоздания
-- таблицы нельзя. Теперь он всегда 0 и работает как обычный дедуп по ключу —
-- повторная доставка с шины даёт ту же строку.

ALTER TABLE waf.audit
    DROP COLUMN IF EXISTS completeness,
    DROP COLUMN IF EXISTS inspectors_missing
