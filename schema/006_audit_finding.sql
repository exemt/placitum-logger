-- Находки инспекторов: одна строка на элемент findings[] сообщения
-- kind=inspector, форма — docs/messages/inspector-audit.schema.ts.
--
-- Таблица одна на всех инспекторов, а не своя на каждого. Находка уже
-- унифицирована на проводе: правило CRS у modsec, совпадение списка у ip, класс
-- уязвимости у vlai, нарушение контракта у json — всё это {code, severity,
-- target, rule}. Пока форма общая, таблица на инспектора означала бы одну и ту
-- же схему, размноженную по DDL, и ветку в логгере на каждый новый движок;
-- "найди все находки по правилу" при этом превращалось бы в UNION по всем
-- спутникам, растущий вместе с их числом.
--
-- Своё у движка остаётся в engine: строкой JSON, как прислал инспектор.
-- Фильтровать по нему никто не будет — по нему смотрят, когда запись уже нашли,
-- ровно как по локаторам обменника на позвоночнике.
--
-- verdict, score, profile и engine_ms повторяются на каждой строке находки
-- одного события. Это плата за то, что "все deny по правилу 913100 в профиле
-- strict" читаются одной таблицей, без JOIN с позвоночником: находок на событие
-- единицы, а запрос по правилу — основной.

CREATE TABLE IF NOT EXISTS waf.audit_finding
(
    -- Ключ склейки с waf.audit тот же: ray — UUID запроса, сквозной по контуру.
    -- rid сюда не попадает вовсе: это слот воркера, он переиспользуется.
    ts    DateTime64(3),
    node  LowCardinality(String),
    ray   String,
    phase LowCardinality(String),

    -- Редакция записи: опоздавший фрагмент не переписывает строку на месте, а
    -- вставляется заново с rev+1, и ReplacingMergeTree оставляет последнюю.
    rev UInt32,

    -- Кто и с каким профилем отвечал. Профиль здесь, а не только в
    -- inspectors_profile позвоночника: без него "почему на этом маршруте
    -- сработало иначе" требует JOIN на каждый запрос по находкам.
    inspector LowCardinality(String),
    profile   LowCardinality(String),
    verdict   LowCardinality(String),
    score     Int32,
    engine_ms Float32,

    -- Позиция в findings[]. Часть ключа сортировки: два одинаковых по code и
    -- rule совпадения в одном событии — законная пара строк, и без порядкового
    -- номера дедуп схлопнул бы их в одну.
    --
    -- Инспектор без находок всё равно даёт строку: finding_idx 0 с пустым code.
    -- Иначе "не вызвали" и "вызвали, чисто" снова неразличимы.
    finding_idx UInt16,
    code        LowCardinality(String),
    severity    LowCardinality(String),

    -- Где нашли: uri | args | body | conn | header:<имя> | cookie:<имя>.
    -- Единственное место в контуре, где место находки внутри запроса названо.
    target String,

    -- Идентификатор правила в терминах движка. Не всякая находка правиловая:
    -- у вероятностных движков поля нет, и здесь остаётся пустая строка.
    rule LowCardinality(String),

    -- Смещение и длина совпадения внутри объекта из target. length 0 означает,
    -- что движок места не назвал: подсвечивать нечего, offset без длины смысла
    -- не имеет.
    offset Int64,
    length Int64,

    -- Уверенность 0..1 у вероятностных движков. У детерминированных её не
    -- бывает вовсе, и 0 здесь читается как "шкала неприменима", а не "ноль".
    confidence Float32,

    -- Цитата совпавшего фрагмента, до 256 байт. Полный объект достают из
    -- обменника по локатору с позвоночника.
    evidence String,

    -- Своё движка: crs_anomaly_score и crs_threshold у modsec, поколение
    -- снапшота и страна у ip, метки и модель у vlai.
    engine String,

    -- Поиск по правилу и по коду находки — основной сценарий, а ключ сортировки
    -- занят склейкой по ray. Обе колонки закрываются skip-индексом.
    INDEX idx_rule rule TYPE bloom_filter GRANULARITY 4,
    INDEX idx_code code TYPE bloom_filter GRANULARITY 4
)
ENGINE = ReplacingMergeTree(rev)
PARTITION BY toDate(ts)
ORDER BY (node, ray, phase, inspector, finding_idx)
TTL toDate(ts) + INTERVAL 90 DAY DELETE
