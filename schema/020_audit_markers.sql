-- Маркеры записи: секция markers, как её собрал модуль из просьб `do: mark`
-- (docs/inspector-actions.md#маркеры). Метку называет оператор в профиле
-- отправителя -- произвольная строка, которую никто по дороге не толкует.
--
-- Массив, а не колонка со строкой JSON, в отличие от actions и rewrite: по
-- маркерам ищут и группируют -- «все события, помеченные bot-farm», «каких
-- меток сколько за сутки», -- и has() по массиву отвечает на первое без
-- разбора строки на каждой строке таблицы, а arrayJoin на второе.
--
-- LowCardinality: строки пишет оператор, и их десятки на весь контур, а не
-- по одной на запрос. Bloom-индекс -- ради has() под фильтром: маркер
-- обычно стоит на малой доле окна, и без индекса это чтение всех гранул.
--
-- Кто поставил метку, сюда не попадает: маркеры -- множество (одна и та же
-- метка от двух инспекторов даёт один элемент), а отправитель и повод видны
-- в actions той же записи. Параллельного массива markers_by нет намеренно:
-- он сломал бы и дедупликацию, и группировку.
--
-- Пустой массив -- обычное состояние: никто ничего не пометил.
ALTER TABLE waf.audit
    ADD COLUMN IF NOT EXISTS markers Array(LowCardinality(String)),
    ADD INDEX IF NOT EXISTS idx_markers markers
        TYPE bloom_filter(0.01) GRANULARITY 4;
