-- Код, который вернуло приложение, отдельно от кода, который получил клиент.
--
-- В status стоит наш ответ: страница отказа, 503 по политике дедлайна, код
-- апстрима при allow. Один и тот же 418 там означает и «приложение ответило
-- успехом, а мы закрыли ответ», и «мы закрыли запрос, приложение не отвечало
-- вовсе» -- а это первый вопрос при разборе инцидента фазы ответа.
--
-- Ноль означает «апстрим не отвечал»: у фазы запроса так всегда, у фазы ответа
-- -- когда до апстрима не дошло. Кода 0 в HTTP нет, и путать его не с чем.

ALTER TABLE waf.audit
    ADD COLUMN IF NOT EXISTS upstream_status UInt16 AFTER status;
