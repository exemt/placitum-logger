-- Журнал процессов получает ключ сортировки, который начинается со времени.
-- Ключ у MergeTree на месте не меняется (MODIFY ORDER BY умеет только
-- дописывать колонки в хвост), поэтому таблица пересоздаётся тем же ходом, что
-- позвоночник в 024–027: 032 создаёт новую рядом, 033 меняет их местами, 034
-- переливает старые строки, 035 сносит старую.
--
-- Почему ts впереди. Ключ (writer, service, ts) из 013 отвечал на «что писала
-- эта нода», но страница журнала спрашивает другое: последние строки окна в
-- порядке времени. На старом ключе время упорядочено только внутри пары
-- writer/service, и ORDER BY ts DESC LIMIT 32 читал окно целиком вместе с
-- колонкой text: на стенде сутки -- 13.8 млн строк и 3.1 ГБ ради одной
-- страницы, секунда-три на каждый клик по фильтру. С ts в голове страница
-- читается с хвоста ключа и останавливается на LIMIT, а окно отсекается
-- первичным индексом.
--
-- writer и service из ключа не пропадают, а уходят в хвост: гранулы они больше
-- не отсекают, и фильтр по ним стоит чтения двух узких LowCardinality-колонок
-- по окну. Это дёшево -- так же у позвоночника читаются verdict и code.
--
-- Колонки и индекс -- как в 013, один в один: логгер пишет в таблицу по имени
-- и после подмены не должен заметить разницы.

CREATE TABLE IF NOT EXISTS waf.log_v2
(
    ts       DateTime64(3),
    writer   LowCardinality(String),
    service  LowCardinality(String),
    severity LowCardinality(String),
    text     String,

    INDEX idx_text lower(text)
        TYPE ngrambf_v1(3, 8192, 3, 0) GRANULARITY 4
)
ENGINE = MergeTree
PARTITION BY toDate(ts)
ORDER BY (ts, writer, service)
TTL toDate(ts) + INTERVAL 14 DAY DELETE
