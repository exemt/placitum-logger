-- Правка ответа: секция rewrite участников записи kind=request.
--
-- Колонкой на позвоночнике и строкой JSON -- по тем же двум причинам, что
-- actions. По правке не фильтруют: её смотрят, когда запись уже нашли, отвечая
-- на один вопрос -- «архив хранит одно, клиент получил другое, кто это сделал».
-- Спутник ради этого означал бы JOIN на каждую карточку.
--
-- Ключ карты -- имя инспектора, значение -- его секция как прислал модуль:
-- applied (подняли ли объект именно его), size (длина подменённого тела) и
-- groups (какие группы модификаторов сработали). Разложить по картам, как
-- verdict и score, нельзя: applied у выключенной правки живёт рядом с groups,
-- и три карты вместо одной строки разъехались бы при первой же потере.
--
-- Пусто -- обычное состояние: правку никто не заказывал либо инспектора на
-- маршруте нет.
ALTER TABLE waf.audit
    ADD COLUMN IF NOT EXISTS rewrite String;
