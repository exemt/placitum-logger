-- Просьбы инспекторов друг к другу: секция actions записи kind=request.
--
-- Колонкой на позвоночнике, а не таблицей-спутником, и строкой JSON, а не
-- разобранными полями. Причина та же, по которой так лежит engine у находки:
-- по действиям не фильтруют. Их смотрят, когда запись уже нашли, отвечая на
-- один вопрос -- "ip просил капчу, капчи не было, почему". Спутник ради этого
-- означал бы JOIN на каждую карточку и ключ сортировки, которым никто не
-- воспользуется.
--
-- Исход просьбы сюда не попадает и попасть не может: его называет получатель в
-- своём kind=inspector, и это отдельное сообщение, приходящее позже. Склейка --
-- в запросе карточки, по ray, как и всё остальное.
--
-- Пусто -- обычное состояние: никто ни о чём не просил либо канал на маршруте
-- выключен (waf_actions_max 0).
ALTER TABLE waf.audit
    ADD COLUMN IF NOT EXISTS actions String;
