-- Логи процессов ноды: строки access_log и error_log nginx, которые агент
-- снимает со своего сокета и кладёт в WAF_LOG.
--
-- Зерно — строка текста, а не запрос. С waf.audit таблица не связана и связана
-- быть не может: в access-строке нет ray, а error_log пишется и там, где
-- запроса не было вовсе (reload, upstream, сам конфиг). Класть их в
-- позвоночник значило бы завести половину колонок пустыми и сломать
-- ReplacingMergeTree, у которого ключ дедупа — как раз ключ запроса.
--
-- Три поля отвечают на три вопроса, и они же и есть фильтры: кто записал
-- (writer — нода, чей агент строку принял), что за сервис (service — тег
-- syslog из самой директивы nginx) и что там было (text). Уровень едет рядом,
-- потому что syslog отдаёт его даром, а access от error без него не отличить.
--
-- MergeTree, а не ReplacingMergeTree: естественного ключа у строки лога нет.
-- Две одинаковые строки в одну миллисекунду — законная пара, и дедуп по
-- содержимому схлопнул бы их в одну. Цена — повтор пачки при сорванной
-- вставке: сообщение уедет на повтор, и строки лягут дважды. Для журнала это
-- дешевле, чем терять повторяющиеся строки на каждой вставке.
--
-- Ключ сортировки ведёт с writer и service: это единственные два фильтра
-- точного совпадения, и по ним же смотрят «что писала эта нода». Текст
-- ищется подстрокой, поэтому у него не место в ключе, а ngram-индекс.
--
-- Индекс стоит на lower(text), и запрос обязан повторить это выражение:
-- LIKE по lower(...) его включает, positionCaseInsensitive — нет, для
-- планировщика это другая функция. То же правило, что у body_preview.
--
-- TTL короче, чем у аудита: логи прирастают на порядок быстрее, а отвечают
-- на вопросы последних дней. Инцидент месячной давности разбирают по
-- waf.audit, где для этого есть всё.

CREATE TABLE IF NOT EXISTS waf.log
(
    ts       DateTime64(3),
    writer   LowCardinality(String),
    service  LowCardinality(String),
    severity LowCardinality(String),
    text     String,

    INDEX idx_text lower(text)
        TYPE ngrambf_v1(3, 8192, 3, 0) GRANULARITY 4
)
ENGINE = MergeTree
PARTITION BY toDate(ts)
ORDER BY (writer, service, ts)
TTL toDate(ts) + INTERVAL 14 DAY DELETE
;
