-- Признак урезанной пары превью и счёт выброшенных пар.
--
-- До потолка на пару признак был не нужен: секция обрывалась целыми парами, и
-- сравнение headers_count и args_size с длиной карты отвечало, всё ли доехало.
-- Второй размер waf_preview режет отдельное значение внутри пары, и на этот
-- вопрос сравнение уже не отвечает: длина карты прежняя, а значение — префикс.
--
-- Имена списком, а не пометкой внутри значения: пометка попала бы в поиск по
-- содержимому — а ищут именно по нему. LowCardinality — имена заголовков и
-- параметров повторяются от записи к записи, множество их на маршруте невелико.
--
-- Выброшенные пары считаются числом, а не перечисляются: выбрасывается пара,
-- у которой имя заняло больше половины потолка, и перечислить их значило бы
-- записать те самые имена, ради невлезаемости которых пара и выброшена. Число
-- отвечает на единственный разрешимый здесь вопрос — полна ли секция.

ALTER TABLE waf.audit
    ADD COLUMN IF NOT EXISTS headers_preview_truncated Array(LowCardinality(String)),
    ADD COLUMN IF NOT EXISTS args_preview_truncated    Array(LowCardinality(String)),
    ADD COLUMN IF NOT EXISTS headers_preview_dropped   UInt16,
    ADD COLUMN IF NOT EXISTS args_preview_dropped      UInt16
