-- Старые строки переезжают в новую таблицу. Колонки перечислены с обеих
-- сторон, а не `SELECT *`, по той же причине, что в 026.
--
-- Строки, записанные после подмены 033, лежат уже в новой таблице и сюда не
-- попадают: waf.log_v1 с момента переименования никто не пишет.
--
-- Повторный запуск после сорванного перелива (рестарт логгера посреди него)
-- продублирует уже перелитую часть: у MergeTree без ключа склейки схлопнуть
-- её нечем. Это размен самой таблицы (013) -- повтор виден как повтор, а
-- потерянную строку не вернуть, -- и здесь он решается так же, в пользу дубля.
--
-- Чтение в один поток и блок вставки по 64 МБ -- ради памяти, а не скорости.
-- По умолчанию вставка копит блок в 256 МБ и сортирует его под новый ключ, и
-- на стенде (ClickHouse с потолком 2 ГБ на весь сервер) перелив падал на
-- MEMORY_LIMIT_EXCEEDED через семь секунд: сам запрос брал 1.4 ГБ. С этими
-- настройками пик -- 380 МБ, а 35.6 млн строк переливаются за 3.7 минуты на
-- двух ядрах. Всё это время логгер не читает поток: накат идёт до подписки, и
-- пачки ждут его в JetStream.
--
-- Порядок чтения источника -- его старый ключ, то есть по времени вразнобой;
-- вставка сортирует каждый блок под новый ключ сама, и куски, которые от
-- этого пересекаются по времени, сольёт фоновое слияние партиции.

INSERT INTO waf.log (ts, writer, service, severity, text)
SELECT ts, writer, service, severity, text
FROM waf.log_v1
SETTINGS
    max_threads = 1,
    max_insert_threads = 1,
    min_insert_block_size_rows = 262144,
    min_insert_block_size_bytes = 67108864
