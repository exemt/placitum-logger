-- Страна адреса для фильтра и группировки журнала.
--
-- Колонки в waf.audit под неё нет намеренно. Страну знает не модуль, а
-- каталог пространства (ip_countries + ip_country_addresses) -- тот самый,
-- который оператор залил `npm run load-geo`, из которого компилируются паки
-- инспектора адреса и из которого отвечает карточка адреса в панели. Колонка
-- на записи была бы четвёртой копией этих данных и отвечала бы только на
-- то, что записано после её появления; словарь отвечает и на всё, что уже
-- лежит в таблице.
--
-- IP_TRIE -- родной для CH разбор «адрес в сети»: миллион префиксов
-- укладывается в ~70 МиБ и отвечает на dictGet за наносекунды. Ключ
-- сравнивается с client_ip (IPv6), v4-префиксы каталога ложатся в
-- v4-mapped вид сами.
--
-- Источник -- Postgres контроллера напрямую. Пространство в запросе не
-- фильтруется: waf.audit контурная, пространства в ней нет, а префикс
-- принадлежит стране одинаково во всех. Дубль одного префикса из двух
-- пространств словарь схлопывает, и это ровно то, что нужно.
--
-- LIFETIME -- перечитывать каталог сам, без рестарта CH: залили новый
-- GeoLite2 -- в течение четверти часа его видит и журнал. Пока Postgres
-- недоступен, словарь отдаёт прошлую загрузку; если он не загрузился ни
-- разу, ломаются только запросы со страной -- обычный список и остальные
-- фильтры словаря не касаются.
CREATE DICTIONARY IF NOT EXISTS waf.geo_country
(
    prefix String,
    code   String
)
PRIMARY KEY prefix
SOURCE(POSTGRESQL(
    host '${POSTGRES_HOST}'
    port ${POSTGRES_PORT}
    user '${POSTGRES_USER}'
    password '${POSTGRES_PASSWORD}'
    db '${POSTGRES_DB}'
    query 'select a.address as prefix, c.code as code from ip_country_addresses a join ip_countries c on c.id = a.country_id'
))
LAYOUT(IP_TRIE)
LIFETIME(MIN 600 MAX 900)
