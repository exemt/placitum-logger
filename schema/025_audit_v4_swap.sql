-- Новая таблица встаёт под именем waf.audit, старая уходит в waf.audit_v3.
-- С этого мгновения логгер пишет уже в новую, а поиск из неё читает; старые
-- строки переливает следующая миграция, и до её конца журнал показывает
-- только то, что записано после подмены.
--
-- RENAME парой, а не EXCHANGE TABLES, хотя тот атомарен: у EXCHANGE второй
-- запуск меняет таблицы обратно, а RENAME второй раз падает на «audit_v3
-- уже есть», ничего не тронув. Раннер миграций держит замок (waf.schema_lock,
-- internal/migrate), и двух запусков быть не должно, но миграция, которая
-- при сбое замка ломает всё молча, хуже той, что ломается громко.
--
-- Между двумя переименованиями таблицы waf.audit нет доли секунды: батч
-- логгера, попавший в это окно, срывается и уезжает на повтор, как любой
-- сорванный батч; запрос поиска получает ошибку один раз.

RENAME TABLE waf.audit TO waf.audit_v3, waf.audit_v4 TO waf.audit
