-- Новая таблица встаёт под именем waf.log, старая уходит в waf.log_v1. С этого
-- мгновения логгер пишет уже в новую, а поиск из неё читает; старые строки
-- переливает 034, и до её конца журнал показывает только то, что записано
-- после подмены.
--
-- RENAME парой, а не EXCHANGE TABLES, по той же причине, что в 025: второй
-- запуск падает на «log_v1 уже есть», ничего не тронув, а не меняет таблицы
-- обратно.
--
-- Пачка логгера, попавшая между двумя переименованиями, срывается и уезжает на
-- повтор, как любая сорванная пачка.

RENAME TABLE waf.log TO waf.log_v1, waf.log_v2 TO waf.log
