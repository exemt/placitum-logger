-- Uuid маршрута рядом с именем блока location.
--
-- Колонка location хранит имя блока nginx, каким его напечатал модуль: для
-- regex-пути это сам паттерн. По нему трафик маршрута уже сворачивается --
-- URI разные, а имя одно, -- но ключ этот хрупкий: паттерн переписывают,
-- prefix переводят в regex, один и тот же паттерн живёт на двух серверах,
-- и из журнала некуда перейти, потому что у строки нет адреса в панели.
--
-- location_id -- uuid пути из waf_route_id, который контроллер печатает в
-- каждый блок location. Он переживает правку паттерна и однозначен в
-- контуре; по нему журнал группирует (ось route) и фильтрует (route=),
-- а панель ведёт со строки журнала на карточку пути.
--
-- LowCardinality: мощность -- число путей в конфигурации, а не число
-- запросов. Пусто у записей от модуля без директивы и у конфигураций,
-- собранных не контроллером; фильтр по пустому не нужен, поэтому Nullable
-- здесь ни к чему.
--
-- Имя блока остаётся: по нему читают, по uuid схлопывают.

ALTER TABLE waf.audit
    ADD COLUMN IF NOT EXISTS location_id LowCardinality(String) AFTER location;
